/**
 * Forensic cases whose primary public record is in a non-English language.
 * English dossier text is translated/synthesized for the archive; originals cited below.
 */
import type { CaseEnrichment } from "@/data/catalog";
import type { SeedCase } from "@/data/seed";
import {
  buildMultilingualDeep,
} from "@/lib/deepContentBuilder";
import { buildDeepForensicAnalysis } from "@/lib/deepAnalysis";
import { buildCaseReferences } from "@/lib/caseReferences";
import { parseCaseContext } from "@/lib/caseContextDepth";
import type {
  CaseReference,
  CaseStatus,
  CountryCode,
  CrimeCategory,
  PsychologicalFactor,
  SourceRef,
  TheoreticalFramework,
} from "@/lib/types";

export type MultilingualSource = SourceRef & {
  originalTitle: string;
  language: string;
  languageLabel: string;
};

export type MultilingualReference = CaseReference & {
  originalCitation: string;
  language: string;
  languageLabel: string;
};

export type MultilingualCaseDef = {
  slug: string;
  name: string;
  nameOriginal?: string;
  subtitle: string;
  country: CountryCode;
  location: string;
  jurisdiction: string;
  yearStart: number;
  yearEnd?: number;
  era: string;
  status: CaseStatus;
  crimeCategories: CrimeCategory[];
  overview: string;
  offenderName: string;
  offenderNameOriginal?: string;
  primarySourceLanguage: string;
  primarySourceLanguageLabel: string;
  translationNote: string;
  sources: MultilingualSource[];
  references: MultilingualReference[];
  lat: number;
  lng: number;
  tags?: string[];
  psychologicalFactors?: PsychologicalFactor[];
  theoreticalFrameworks?: TheoreticalFramework[];
};

function buildAnalysis(d: MultilingualCaseDef, deep: ReturnType<typeof buildMultilingualDeep>) {
  return buildDeepForensicAnalysis({
    slug: d.slug,
    name: d.name,
    subtitle: d.subtitle,
    overview: d.overview,
    jurisdiction: d.jurisdiction,
    location: d.location,
    era: d.era,
    yearStart: d.yearStart,
    yearEnd: d.yearEnd,
    status: d.status,
    crimeCategories: d.crimeCategories,
    offenderName: d.offenderName,
    signals: deep.signals,
    narrative: deep.narrative,
    timeline: deep.timeline,
    behavioralProfile: deep.enrichmentPatch.behavioralProfile,
    motivationalFactors: deep.enrichmentPatch.motivationalFactors,
    psychologicalFactors: d.psychologicalFactors ?? ["antisocial_traits", "power_control"],
    theoreticalFrameworks: d.theoreticalFrameworks ?? ["personality", "situational"],
    primarySourceLanguageLabel: d.primarySourceLanguageLabel,
    translationNote: d.translationNote,
    published: true,
  });
}

function multilingualDeepInput(d: MultilingualCaseDef) {
  return {
    slug: d.slug,
    name: d.name,
    subtitle: d.subtitle,
    overview: d.overview,
    jurisdiction: d.jurisdiction,
    location: d.location,
    era: d.era,
    yearStart: d.yearStart,
    yearEnd: d.yearEnd,
    status: d.status,
    crimeCategories: d.crimeCategories,
    offenderName: d.offenderName,
    offenderBackground: d.offenderNameOriginal
      ? `Documented in ${d.primarySourceLanguageLabel} press and court files as ${d.offenderNameOriginal}.`
      : undefined,
    nameOriginal: d.nameOriginal,
    offenderNameOriginal: d.offenderNameOriginal,
    primarySourceLanguage: d.primarySourceLanguage,
    primarySourceLanguageLabel: d.primarySourceLanguageLabel,
    translationNote: d.translationNote,
    sourceTitles: d.sources.map((s) => s.originalTitle ?? s.title),
    references: d.references,
  };
}

function toSeed(d: MultilingualCaseDef): SeedCase {
  const input = multilingualDeepInput(d);
  const deep = buildMultilingualDeep(input);
  return {
    id: `case-${d.slug}`,
    slug: d.slug,
    name: d.name,
    nameOriginal: d.nameOriginal,
    subtitle: d.subtitle,
    jurisdiction: d.jurisdiction,
    era: d.era,
    status: d.status,
    tags: [...(d.tags ?? []), "multilingual-source", "translated-en", "deep-dossier"],
    warning:
      "English summary translated from non-English public sources. Consult original-language citations. Not legal or clinical advice.",
    overview: deep.expandedOverview,
    primarySourceLanguage: d.primarySourceLanguage,
    primarySourceLanguageLabel: d.primarySourceLanguageLabel,
    translationNote: d.translationNote,
    timeline: deep.timeline,
    signals: deep.signals,
    sources: d.sources.map(({ originalTitle, language, languageLabel, ...rest }) => ({
      ...rest,
      originalTitle,
      language,
      languageLabel,
    })),
    analysis: buildAnalysis(d, deep),
  };
}

function toEnrichment(d: MultilingualCaseDef): CaseEnrichment {
  const patch = buildMultilingualDeep(multilingualDeepInput(d)).enrichmentPatch;
  return {
    location: d.location,
    country: d.country,
    yearStart: d.yearStart,
    yearEnd: d.yearEnd,
    crimeCategories: d.crimeCategories,
    psychologicalFactors: d.psychologicalFactors ?? ["antisocial_traits"],
    theoreticalFrameworks: d.theoreticalFrameworks ?? ["personality", "situational"],
    diagnoses: [
      {
        label: "Forensic hypotheses (non-diagnostic)",
        status: "hypothesized",
        note: `Inferences drawn from ${d.primarySourceLanguageLabel} public record, rendered in English.`,
      },
    ],
    offenders: patch.offenders ?? [
      {
        id: `off-${d.slug}`,
        name: d.offenderName,
        role: "offender",
        known: d.offenderName !== "Unknown",
        sex: "male",
        background: d.offenderNameOriginal
          ? `Known in ${d.primarySourceLanguageLabel} sources as ${d.offenderNameOriginal}.`
          : "See original-language court records.",
      },
    ],
    victims: patch.victims ?? [{ id: `vic-${d.slug}`, name: "Victims (public record)", role: "victim", known: true }],
    legalOutcome: patch.legalOutcome ?? {
      summary: "See original-language court documents in References.",
    },
    behavioralProfile: patch.behavioralProfile ?? {
      modusOperandi: "See English overview; verify phrasing against originals.",
      organizationLevel: "mixed",
    },
    motivationalFactors: patch.motivationalFactors ?? [
      { label: "Source-language narratives", detail: d.translationNote },
    ],
    relatedCaseSlugs: [],
    documentIds: [],
    references: buildCaseReferences(
      parseCaseContext({
        slug: d.slug,
        name: d.name,
        subtitle: d.subtitle,
        overview: d.overview,
        jurisdiction: d.jurisdiction,
        location: d.location,
        era: d.era,
        yearStart: d.yearStart,
        yearEnd: d.yearEnd,
        status: d.status,
        crimeCategories: d.crimeCategories,
        offenderName: d.offenderName,
        offenderBackground: d.offenderNameOriginal
          ? `Known in ${d.primarySourceLanguageLabel} sources as ${d.offenderNameOriginal}.`
          : undefined,
      }),
      {
        existing: d.references.map(({ originalCitation, language, languageLabel, ...rest }) => ({
          ...rest,
          originalCitation,
          language,
          languageLabel,
        })),
      },
    ),
    nameOriginal: d.nameOriginal,
    primarySourceLanguage: d.primarySourceLanguage,
    primarySourceLanguageLabel: d.primarySourceLanguageLabel,
    translationNote: d.translationNote,
  };
}

